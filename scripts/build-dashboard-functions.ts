// Builds single-file copies of the Edge Functions for the Supabase dashboard editor
// (Edge Functions > Deploy a new function > Via Editor), which cannot import from ../_shared.
// Run after changing anything in supabase/functions:  node scripts/build-dashboard-functions.ts
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = 'supabase/functions';
const outDir = 'supabase/dashboard';
const shared: Record<string, string> = {
  loyalty: `${root}/_shared/loyalty.ts`,
  token: `${root}/_shared/token.ts`,
  'api-types': `${root}/_shared/api-types.ts`,
  server: `${root}/_shared/server.ts`,
};

/** Drop import lines and `export` keywords: everything ends up in one module. */
function inline(path: string): string {
  return readFileSync(path, 'utf8')
    .split('\n')
    .filter((l) => !/^import\s/.test(l))
    .map((l) => l.replace(/^export (?=(async |function|const|type|class|let))/, ''))
    .join('\n')
    .trim();
}

mkdirSync(outDir, { recursive: true });
for (const fn of ['collect', 'redeem', 'delete-account']) {
  const src = readFileSync(`${root}/${fn}/index.ts`, 'utf8');
  const used = [...src.matchAll(/from '\.\.\/_shared\/([\w-]+)\.ts'/g)].map((m) => m[1]);
  // api-types needs ProgramType from loyalty; server is always needed for the npm import.
  const parts = ['loyalty', 'token', 'api-types', 'server'].filter((p) => used.includes(p) || (p === 'loyalty' && used.includes('api-types')));
  const body = src
    .split('\n')
    .filter((l) => !/^import\s.*_shared/.test(l))
    .join('\n')
    .trim();
  const out = [
    `// GENERATED by scripts/build-dashboard-functions.ts from supabase/functions/${fn}/index.ts. Do not edit:`,
    '// change the source and run the script again. Paste this whole file into the dashboard editor',
    `// as the function "${fn}".`,
    "import { createClient, type SupabaseClient } from 'npm:@supabase/supabase-js@2';",
    '',
    ...parts.map((p) => `// ---- _shared/${p}.ts\n${inline(shared[p])}\n`),
    `// ---- ${fn}/index.ts`,
    body,
    '',
  ].join('\n');
  writeFileSync(`${outDir}/${fn}.ts`, out);
  console.log(`${outDir}/${fn}.ts`);
}
