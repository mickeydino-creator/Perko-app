// Turns the wordmark into vector paths: "perk" in Heebo 800 with the website's geometry
// (src/components/Wordmark.astro of Perko-marketing): tracking -0.055em, a 0.035em gap, and a 0.5em disc as the "o"
// whose bottom sits on the baseline (+0.015em). Drawing it as paths makes it identical on iOS, Android and web,
// whatever each platform does with font metrics. Run: node scripts/generate-wordmark.ts
import fontkit from '@pdf-lib/fontkit';
import { readFileSync, writeFileSync } from 'node:fs';

const font = fontkit.create(readFileSync('node_modules/@expo-google-fonts/heebo/800ExtraBold/Heebo_800ExtraBold.ttf'));
const em = font.unitsPerEm;
const tracking = -0.055 * em;
const gap = 0.035 * em;
const r = 0.25 * em;
const discBottom = -0.015 * em; // CSS translateY(0.015em): slightly below the baseline, like the round letters

const run = font.layout('perk');
let pen = 0;
const glyphs = run.glyphs.map((g, i) => {
  const at = pen;
  pen += run.positions[i].xAdvance + tracking;
  return { g, at };
});
const top = Math.max(...run.glyphs.map((g) => g.bbox.maxY));
const bottom = Math.min(...run.glyphs.map((g) => g.bbox.minY), discBottom);
const cx = pen + gap + r;
const cy = discBottom + r;
const width = cx + r;
const height = top - bottom;

const round = (s: string) => s.replace(/-?\d+\.\d+/g, (n) => String(Math.round(Number(n) * 10) / 10));
// Font coordinates are y-up; SVG is y-down with the top of the "k" at 0.
// @pdf-lib/fontkit's types omit Path.scale/translate, which exist at runtime.
type Movable = { scale(x: number, y: number): Movable; translate(x: number, y: number): Movable; toSVG(): string };
const letters = glyphs.map(({ g, at }) => round((g.path as unknown as Movable).scale(1, -1).translate(at, top).toSVG())).join('');

const out = `// GENERATED by scripts/generate-wordmark.ts from Heebo 800. Do not edit by hand.
// Units: font units (1 em = ${em}). Baseline at y = ${Math.round(top)}.
export const WORDMARK = {
  em: ${em},
  width: ${Math.round(width)},
  height: ${Math.round(height)},
  letters: '${letters}',
  disc: { cx: ${Math.round(cx)}, cy: ${Math.round(top - cy)}, r: ${Math.round(r)} },
} as const;
`;
writeFileSync('src/components/wordmarkPath.ts', out);
console.log('src/components/wordmarkPath.ts', Math.round(width), 'x', Math.round(height));
